const generatedMarkdownMarker = "<!-- Generated by rza_migrate_report. Edit source SQL, not this file. -->\n\n"
const layoutSchema = "RZA_DATABASE_DOCUMENTATION_V2"

type layoutManifest struct {
	Schema      string            `json:"schema"`
	GeneratedAt string            `json:"generated_at"`
	Repository  string            `json:"repository"`
	Sources     []string          `json:"sources"`
	Roots       map[string]string `json:"roots"`
	RootPaths   map[string]string `json:"root_paths"`
	Artifacts   []ReportArtifact  `json:"artifacts"`
	HashPolicy  string            `json:"hash_policy"`
}

func auditArtifactFiles() []string {
	return []string{"README.md", "datasets/report_summary.csv", "datasets/migration_summary.csv", "datasets/object_history.csv", "datasets/table_changes.csv", "datasets/index_changes.csv", "datasets/programmable_changes.csv", "datasets/type_changes.csv", "report.json"}
}

func writeGeneratedMarkdown(path, body string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(generatedMarkdownMarker+body), 0644)
}

func documentLink(fromDir, target string) string {
	rel, err := filepath.Rel(fromDir, target)
	if err != nil {
		return (&url.URL{Scheme: "file", Path: "/" + filepath.ToSlash(target)}).String()
	}
	return (&url.URL{Path: filepath.ToSlash(rel)}).String()
}

func renderDocumentationIndex(docsDir, outDir string, res *RunResult) string {
	return fmt.Sprintf("# Database Documentation\n\nDokumentasi ini dibuat dari source repository secara offline, tanpa koneksi database atau eksekusi SQL.\n\n## Reading order\n\n1. [Identifiers dan kandidat JOIN](identifiers/table_unique_ids.md): enforcement uniqueness, row-ID signal, dan evidence kandidat JOIN.\n2. [Relationship diagrams](relationships/relational_erd.md): diagram relasi beserta exact column mapping.\n3. [Relationship catalog](relationships/relationship_catalog.md): declared FK dan observed JOIN dengan source evidence.\n4. [Module lineage](relationships/module_lineage.md): dependency view/procedure dan dynamic-SQL review.\n5. [Procedure profiles](procedures/README.md): alur proses serta direct/recursive data impact.\n6. [Migration history](%s): ringkasan perubahan dari migration history.\n\n## Analysis summary\n\n- Migration status: **%s**; analyzed pairs: **%d**; excluded bootstrap pairs: **%d**.\n- Warnings: **%d**; errors: **%d**.\n- Sumber dokumentasi current state: `db_object/`; sumber histori: `migrations/`. Current state dan histori dapat berbeda.\n- Observed JOIN/IDENTITY/nama kolom tidak membuktikan uniqueness. Static analysis tidak membuktikan runtime branch atau isi data.\n\n## File inventory\n\n[Manifest dan SHA-256 seluruh hasil](manifest.json). Nama dan lokasi hasil stabil antar-run; waktu pembuatan tersedia pada manifest. File manual di luar nama hasil generator tetap dipertahankan.\n",
		documentLink(docsDir, filepath.Join(outDir, "README.md")), res.Summary.Status, res.Summary.TotalPairs, res.Summary.ExcludedPairs, res.Summary.Warnings, res.Summary.Errors)
}

func renderMigrationIndex(docsDir, outDir string, res *RunResult) string {
	var b strings.Builder
	b.WriteString("# Migration History\n\n")
	fmt.Fprintf(&b, "[Database documentation](%s) · [JSON report](report.json)\n\n", documentLink(outDir, filepath.Join(docsDir, "README.md")))
	fmt.Fprintf(&b, "Status: **%s**. Files scanned: **%d**; analyzed pairs: **%d**; excluded bootstrap pairs: **%d**; objects: **%d**; operations: **%d**.\n\n", res.Summary.Status, res.Summary.TotalFiles, res.Summary.TotalPairs, res.Summary.ExcludedPairs, res.Summary.TotalObjects, res.Summary.TotalOperations)
	b.WriteString("## Datasets\n\nCSV memakai UTF-8 tanpa BOM dan RFC 4180.\n\n")
	for _, path := range auditArtifactFiles() {
		if strings.HasSuffix(path, ".csv") {
			fmt.Fprintf(&b, "- [%s](%s)\n", filepath.Base(path), path)
		}
	}
	b.WriteString("\n## Findings\n\n")
	if len(res.Warnings)+len(res.Errors) == 0 {
		b.WriteString("Tidak ada warning atau error pada analisis histori.\n")
	}
	for _, finding := range res.Warnings {
		fmt.Fprintf(&b, "- Warning: `%s`\n", md(finding))
	}
	for _, finding := range res.Errors {
		fmt.Fprintf(&b, "- Error: `%s`\n", md(finding))
	}
	return b.String()
}

// publishReportBundle stages complete output before checking paths or changing published files.
func publishReportBundle(repoRoot, docsDir, outDir string, res *RunResult) error {
	stage, err := os.MkdirTemp("", "rza-report-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage) // A fresh, tool-owned temporary directory, never a user output directory.
	roots := map[string]string{"documentation_directory": docsDir, "output_directory": outDir}
	staged := map[string]string{"documentation_directory": filepath.Join(stage, "docs"), "output_directory": filepath.Join(stage, "audit")}
	if err := WriteDesiredStateDocs(staged["documentation_directory"], res.DesiredStateDocs); err != nil {
		return err
	}
	if err := WriteReports(staged["output_directory"], res); err != nil {
		return err
	}
	if err := writeGeneratedMarkdown(filepath.Join(staged["documentation_directory"], "README.md"), renderDocumentationIndex(docsDir, outDir, res)); err != nil {
		return err
	}
	if err := writeGeneratedMarkdown(filepath.Join(staged["output_directory"], "README.md"), renderMigrationIndex(docsDir, outDir, res)); err != nil {
		return err
	}
	manifest := layoutManifest{Schema: layoutSchema, GeneratedAt: res.JSONReport.GeneratedAt, Repository: repoRoot, Sources: []string{"db_object/", "migrations/"}, Roots: roots, Artifacts: append([]ReportArtifact(nil), res.JSONReport.Artifacts...), HashPolicy: "SHA-256 of exact file bytes; manifest.json excludes its own hash"}
	manifest.RootPaths = map[string]string{"documentation_directory": "."}
	if relative, err := filepath.Rel(docsDir, outDir); err == nil {
		manifest.RootPaths["output_directory"] = filepath.ToSlash(relative)
	}
	if err := validateArtifactPath(repoRoot, docsDir, "manifest.json"); err != nil {
		return err
	}
	previous, err := readLayoutManifest(filepath.Join(docsDir, "manifest.json"))
	if err != nil {
		return err
	}
	if previous == nil {
		previous, err = previousAuditOwner(repoRoot, outDir)
		if err != nil {
			return err
		}
	}
	paths := map[string]bool{}
	contents := map[string][]byte{}
	for i := range manifest.Artifacts {
		a := &manifest.Artifacts[i]
		target := filepath.Join(roots[a.Root], filepath.FromSlash(a.Path))
		if err := validateArtifactPath(repoRoot, roots[a.Root], a.Path); err != nil {
			return err
		}
		resolved, err := resolvePathForContainment(target)
		if err != nil {
			return err
		}
		key := pathIdentity(resolved)
		if paths[key] {
			return fmt.Errorf("report output paths overlap at %s; use a separate -out directory or omit -out", target)
		}
		paths[key] = true
		if a.Path == "manifest.json" && a.Root == "documentation_directory" {
			continue
		}
		data, err := os.ReadFile(filepath.Join(staged[a.Root], filepath.FromSlash(a.Path)))
		if err != nil {
			return err
		}
		contents[target] = data
		a.SHA256 = contentHash(data)
		if err := validateExistingOutput(target, data, previous); err != nil {
			return err
		}
	}
	// Each file is replaced atomically; the complete inventory is published last.
	var targets []string
	for target := range contents {
		targets = append(targets, target)
	}
	sort.Strings(targets)
	for _, target := range targets {
		if err := replaceReportFile(target, contents[target]); err != nil {
			return err
		}
	}
	if err := removeStaleArtifacts(repoRoot, previous, roots, paths); err != nil {
		return err
	}
	if err := cleanLegacyLayout(repoRoot, docsDir, outDir, res); err != nil {
		return err
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	return replaceReportFile(filepath.Join(docsDir, "manifest.json"), append(data, '\n'))
}

func readLayoutManifest(path string) (*layoutManifest, error) {
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var m layoutManifest
	if json.Unmarshal(data, &m) != nil || m.Schema != layoutSchema || m.Roots["documentation_directory"] == "" || m.Roots["output_directory"] == "" {
		return nil, fmt.Errorf("unrecognized documentation manifest %s; move the manual file or choose another -docs root", path)
	}
	// Relative root locations make ownership portable across clones and OSes.
	// Absolute roots remain provenance; a cross-volume root stays absolute.
	for key, relative := range m.RootPaths {
		if (key == "documentation_directory" || key == "output_directory") && !filepath.IsAbs(filepath.FromSlash(relative)) {
			m.Roots[key] = filepath.Clean(filepath.Join(filepath.Dir(path), filepath.FromSlash(relative)))
		}
	}
	return &m, nil
}

// A retained explicit -out can outlive a change of -docs. Its report points to
// the previous manifest, whose hash must authenticate that existing report.
func previousAuditOwner(repoRoot, outDir string) (*layoutManifest, error) {
	if err := validateArtifactPath(repoRoot, outDir, "report.json"); err != nil {
		return nil, err
	}
	data, err := os.ReadFile(filepath.Join(outDir, "report.json"))
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var report JSONReport
	if json.Unmarshal(data, &report) != nil {
		return nil, nil
	}
	if report.DocumentationIndex != "" {
		index := filepath.FromSlash(report.DocumentationIndex)
		if !filepath.IsAbs(index) {
			index = filepath.Join(outDir, index)
		}
		if filepath.Base(index) == "README.md" {
			report.DocumentationDirectory = filepath.Dir(index)
		}
	}
	if report.DocumentationDirectory == "" || !filepath.IsAbs(report.DocumentationDirectory) {
		return nil, nil
	}
	if err := validateArtifactPath(repoRoot, report.DocumentationDirectory, "manifest.json"); err != nil {
		return nil, nil
	}
	owner, err := readLayoutManifest(filepath.Join(report.DocumentationDirectory, "manifest.json"))
	if err != nil || owner == nil || pathIdentity(owner.Roots["output_directory"]) != pathIdentity(outDir) {
		return nil, nil
	}
	for _, a := range owner.Artifacts {
		if a.Root == "output_directory" && a.Path == "report.json" && a.SHA256 == contentHash(data) {
			return owner, nil
		}
	}
	return nil, nil
}

func pathIdentity(path string) string {
	path = filepath.Clean(path)
	if runtime.GOOS == "windows" {
		return strings.ToLower(path)
	}
	return path
}

func contentHash(data []byte) string {
	hash := sha256.Sum256(data)
	return hex.EncodeToString(hash[:])
}

func validateArtifactPath(repoRoot, root, relative string) error {
	if root == "" || !filepath.IsLocal(filepath.FromSlash(relative)) {
		return fmt.Errorf("unsafe report artifact path: %q", relative)
	}
	target := filepath.Join(root, filepath.FromSlash(relative))
	if err := validateDirectoryOutsideProtected(repoRoot, target, "report artifact"); err != nil {
		return err
	}
	// Reject symlinks in every managed child, including a file symlink. Root aliases
	// themselves are allowed after the protected-source check above.
	for path := target; pathIdentity(path) != pathIdentity(root); path = filepath.Dir(path) {
		info, err := os.Lstat(path)
		if err == nil && info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("report artifact must not traverse a symlink: %s", path)
		}
		if err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	return nil
}

func validateExistingOutput(target string, fresh []byte, previous *layoutManifest) error {
	old, err := os.ReadFile(target)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if bytes.Equal(old, fresh) {
		return nil
	}
	if previous != nil {
		for _, a := range previous.Artifacts {
			if pathIdentity(filepath.Join(previous.Roots[a.Root], filepath.FromSlash(a.Path))) == pathIdentity(target) && a.SHA256 != "" && contentHash(old) == a.SHA256 {
				return nil
			}
		}
	} else if bytes.Equal(normalizeDocument(old), normalizeDocument(legacyMarkdownBody(fresh))) {
		// Upgrade an unchanged legacy document in a location retained by V2.
		return nil
	}
	if previous == nil && filepath.Base(target) == "report.json" && equivalentLegacyReport(old, fresh) {
		return nil
	}
	return fmt.Errorf("preserving unowned or manually modified file %s; move it to a manual filename or choose another output root", target)
}

func replaceReportFile(target string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(target), 0755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(target), ".rza-report-*")
	if err != nil {
		return err
	}
	name := f.Name()
	defer os.Remove(name)
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Chmod(name, 0644); err != nil {
		return err
	}
	return os.Rename(name, target)
}

func removeStaleArtifacts(repoRoot string, previous *layoutManifest, roots map[string]string, current map[string]bool) error {
	if previous == nil {
		return nil
	}
	for _, a := range previous.Artifacts {
		root := roots[a.Root]
		if root == "" || pathIdentity(root) != pathIdentity(previous.Roots[a.Root]) || !ownedArtifactName(a.Root, a.Path) || a.SHA256 == "" {
			continue
		}
		target := filepath.Join(root, filepath.FromSlash(a.Path))
		resolved, err := resolvePathForContainment(target)
		if err != nil {
			continue
		}
		if current[pathIdentity(resolved)] {
			continue
		}
		if err := validateArtifactPath(repoRoot, root, a.Path); err != nil {
			fmt.Fprintf(os.Stderr, "[preserved] unsafe stale report: %s\n", target)
			continue
		}
		data, err := os.ReadFile(target)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return err
		}
		if contentHash(data) != a.SHA256 {
			fmt.Fprintf(os.Stderr, "[preserved] manually modified stale report: %s\n", target)
			continue
		}
		if err := os.Remove(target); err != nil {
			return err
		}
	}
	return nil
}

func ownedArtifactName(root, path string) bool {
	files := auditArtifactFiles()
	if root == "documentation_directory" {
		files = desiredStateReportFiles
		if strings.HasPrefix(path, "procedures/profiles/") && strings.HasSuffix(path, ".md") && !strings.Contains(strings.TrimPrefix(path, "procedures/profiles/"), "/") {
			return true
		}
	}
	for _, file := range files {
		if file == path {
			return true
		}
	}
	return false
}

func normalizeDocument(data []byte) []byte {
	return bytes.TrimSpace(bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n")))
}

func legacyMarkdownBody(data []byte) []byte {
	data = bytes.TrimPrefix(data, []byte(generatedMarkdownMarker))
	for _, link := range []string{"\n[Database documentation](../README.md)\n", "\n[Database documentation](../../README.md)\n"} {
		data = bytes.TrimSuffix(data, []byte(link))
	}
	return data
}

// Legacy files have no ownership hashes. Remove only byte-equivalent regenerated
// documents/datasets; keep changed files and unknown split diagrams for manual review.
func cleanLegacyLayout(repoRoot, docsDir, outDir string, res *RunResult) error {
	for grouped, body := range desiredStateMarkdown(res.DesiredStateDocs) {
		legacy := filepath.Base(grouped)
		if err := removeMatchingLegacy(repoRoot, docsDir, legacy, []byte(body)); err != nil {
			return err
		}
	}
	if err := removeMatchingLegacy(repoRoot, docsDir, "table_relationship_tree.md", []byte(renderRelationshipCompatibilityNotice())); err != nil {
		return err
	}
	legacyRoot := filepath.Join(repoRoot, "out", "report")
	if pathIdentity(legacyRoot) == pathIdentity(outDir) {
		legacyRoot = outDir // Explicit -out keeps its location but CSVs still move to datasets/.
	}
	for _, path := range auditArtifactFiles() {
		if !strings.HasSuffix(path, ".csv") {
			continue
		}
		fresh, err := os.ReadFile(filepath.Join(outDir, filepath.FromSlash(path)))
		if err != nil {
			return err
		}
		if err := removeMatchingLegacy(repoRoot, legacyRoot, filepath.Base(path), fresh); err != nil {
			return err
		}
	}
	if pathIdentity(legacyRoot) != pathIdentity(outDir) {
		old, oldErr := os.ReadFile(filepath.Join(legacyRoot, "report.json"))
		fresh, freshErr := os.ReadFile(filepath.Join(outDir, "report.json"))
		if oldErr == nil && freshErr == nil && equivalentLegacyReport(old, fresh) {
			if err := removeMatchingLegacy(repoRoot, legacyRoot, "report.json", old); err != nil {
				return err
			}
		}
		// Remove only the now-empty legacy report directory, never its parent out/.
		_ = os.Remove(legacyRoot)
	}
	return nil
}

func removeMatchingLegacy(repoRoot, root, relative string, fresh []byte) error {
	if err := validateArtifactPath(repoRoot, root, relative); err != nil {
		fmt.Fprintf(os.Stderr, "[preserved] unsafe legacy report: %s\n", filepath.Join(root, relative))
		return nil
	}
	target := filepath.Join(root, relative)
	old, err := os.ReadFile(target)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !bytes.Equal(normalizeDocument(old), normalizeDocument(fresh)) && !(relative == "report_summary.csv" && equivalentLegacySummary(old, fresh)) {
		fmt.Fprintf(os.Stderr, "[preserved] unverified legacy file: %s\n", target)
		return nil
	}
	return os.Remove(target)
}

func equivalentLegacySummary(old, fresh []byte) bool {
	a, errA := csv.NewReader(bytes.NewReader(old)).ReadAll()
	b, errB := csv.NewReader(bytes.NewReader(fresh)).ReadAll()
	if errA != nil || errB != nil || len(a) != 2 || len(b) != 2 || len(a[0]) == 0 || a[0][0] != "run_at" || b[0][0] != "run_at" {
		return false
	}
	a[1][0], b[1][0] = "", ""
	return reflect.DeepEqual(a, b)
}

func equivalentLegacyReport(old, fresh []byte) bool {
	var a, b map[string]any
	if json.Unmarshal(old, &a) != nil || json.Unmarshal(fresh, &b) != nil {
		return false
	}
	for _, key := range []string{"generated_at", "output_directory", "documentation_directory", "documentation_index", "reports", "artifacts"} {
		delete(a, key)
		delete(b, key)
	}
	return reflect.DeepEqual(a, b)
}
